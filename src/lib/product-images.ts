export function resolveProductImage(filename: string | null | undefined): string {
  if (!filename) return ring;
  if (
    filename.startsWith("http://") ||
    filename.startsWith("https://") ||
    filename.startsWith("/") ||
    filename.startsWith("data:")
  ) return filename;
  return map[filename] ?? ring;
}

